import os
import sys
import time
from dotenv import load_dotenv

# Ensure utf-8 output in Windows console
if sys.platform == "win32":
    sys.stdout.reconfigure(encoding="utf-8")

load_dotenv()

from app import database, sarvam_service
from app.sync_engine import engine

def run_tests():
    print("=" * 70)
    print("🚀 TESTING COMPLETE OFFLINE-FIRST CITIZEN REPORTER PROTOTYPE")
    print("=" * 70)

    # 1. Initialize DB
    print("\n[Step 1] Initializing SQLite local database...")
    database.init_db()
    print("✓ Local edge database initialized.")

    # 2. Test Offline Behavior (Network-Dead Zone Simulation)
    print("\n[Step 2] Simulating OFFLINE / Network-Dead Zone...")
    engine.set_online(False)
    print(f"Network state: {'ONLINE' if engine.is_online() else 'OFFLINE (Low-Bandwidth / Dead Zone)'}")

    marathi_sms = "चिपळूण बाजार पेठेत पाणी भरले आहे, ४ लोक घराच्या छतावर अडकली आहेत. वीज गेली आहे, लवकर मदत पाठवा."
    phone = "+91 98201 12345"

    queue_id = database.add_to_queue(
        report_type="sms",
        caller_phone=phone,
        raw_content=marathi_sms,
        audio_filename=None
    )
    print(f"✓ Citizen sent emergency SMS. Stored locally in SQLite Queue ID: #{queue_id}")

    pending = database.get_pending_queue()
    assert any(q["id"] == queue_id for q in pending), "Report must be in pending queue!"
    print(f"✓ Confirmed: Report #{queue_id} is safely stored on-device (Status: QUEUED).")

    # Verify no incidents created yet on cloud fusion board
    incidents_before = database.get_all_incidents()
    print(f"✓ Fusion board incidents count while offline: {len(incidents_before)}")

    # 3. Test Online Reconnection & Automatic Synchronization Pipeline
    print("\n[Step 3] Simulating Network Reconnection (Edge Gateway catches 2G/4G signal)...")
    engine.set_online(True)
    print(f"Network state: {'ONLINE' if engine.is_online() else 'OFFLINE'}")

    print("Running automatic sync pipeline with Sarvam AI...")
    synced_ids = engine.sync_pending_reports()
    print(f"✓ Sync complete! Synced Incident IDs: {synced_ids}")

    assert len(synced_ids) > 0, "At least one incident should have been synced!"
    incident_id = synced_ids[0]

    # Verify Incident Details in Fusion Board
    incidents = database.get_all_incidents()
    incident = next((i for i in incidents if i["id"] == incident_id), None)
    assert incident is not None, "Incident must exist in database"

    print("\n" + "=" * 70)
    print(f"📋 EMERGENCY FUSION BOARD INCIDENT #{incident['id']}")
    print("=" * 70)
    print(f"• Caller Phone:        {incident['caller_phone']}")
    print(f"• Incident Category:   {incident['category'].upper()}")
    print(f"• Urgency Level:       {incident['urgency']}")
    print(f"• Extracted Location:  {incident['location']}")
    print(f"• Affected Citizens:   ~{incident['affected_count']}")
    print(f"• Detected Language:   {incident['detected_language']}")
    print(f"• Original Report:     {incident['original_text']}")
    print(f"• Sarvam 105B Summary: {incident['english_summary']}")
    print(f"• Regional Advisory:   {incident['regional_advisory_text']}")
    print(f"• Regional Voice TTS:  {incident['advisory_audio_file']}")

    # Check advisory audio file exists on disk
    if incident['advisory_audio_file']:
        audio_full_path = os.path.join(os.path.dirname(__file__), "audio_storage", incident['advisory_audio_file'])
        assert os.path.exists(audio_full_path), f"Audio file {audio_full_path} must exist on disk!"
        file_size = os.path.getsize(audio_full_path)
        print(f"• Audio File Size:     {file_size} bytes (Valid WAV generated by Sarvam Bulbul TTS)")

    # 4. Check Citizen Advisory Inbox
    advisories = database.get_all_advisories()
    print(f"\n✓ Citizen Advisory Inbox contains {len(advisories)} logged safety broadcast(s).")

    print("\n" + "=" * 70)
    print("🎉 ALL PROTOTYPE TESTS PASSED SUCCESSFULLY!")
    print("=" * 70)

if __name__ == "__main__":
    run_tests()

